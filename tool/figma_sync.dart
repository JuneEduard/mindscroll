// Syncs design tokens (colors, text styles) from a Figma file into
// lib/design_tokens.dart — no manual zip downloads needed.
//
// Setup (one-time):
//   1. Figma → Settings → Security → "Personal access tokens" → Generate new token
//   2. setx FIGMA_TOKEN "your-token"   (then restart the terminal)
//
// Usage:
//   dart tool/figma_sync.dart <FILE_KEY>
//
// The file key is the part of the Figma URL after /design/:
//   https://www.figma.com/design/<FILE_KEY>/MindScroll-Dashboard
//
// Only published library styles are synced (colors must be defined as Figma
// styles with descriptive names, e.g. "primary", "surface" — not raw fills).

import 'dart:convert';
import 'dart:io';

Future<void> main(List<String> args) async {
  final token = Platform.environment['FIGMA_TOKEN'];
  if (token == null || token.isEmpty) {
    stderr.writeln('ERROR: FIGMA_TOKEN environment variable not set.');
    exitCode = 1;
    return;
  }
  if (args.isEmpty) {
    stderr.writeln('Usage: dart tool/figma_sync.dart <FILE_KEY>');
    exitCode = 1;
    return;
  }
  final fileKey = args.first;

  final client = HttpClient();
  Future<Map<String, dynamic>> get(String path) async {
    final req = await client.getUrl(Uri.parse('https://api.figma.com$path'))
      ..headers.add('X-Figma-Token', token);
    final res = await req.close().timeout(const Duration(seconds: 15));
    if (res.statusCode != 200) {
      stderr.writeln('Figma API error ${res.statusCode} for $path');
      exitCode = 1;
      throw StateError('API error');
    }
    return jsonDecode(await utf8.decoder.bind(res).join()) as Map<String, dynamic>;
  }

  final styles = await get('/v1/files/$fileKey/styles');
  final styleList = (styles['meta']?['styles'] as List?) ?? [];

  final keys = <String>[];
  for (final s in styleList) {
    keys.add((s as Map<String, dynamic>)['key'] as String);
  }

  final colors = <String, String>{};
  final textStyleNames = <String>[];

  // Resolve each style's concrete value via the batch styles endpoint.
  if (keys.isNotEmpty) {
    final detail = await get('/v1/styles?ids=${keys.join(',')}');
    for (final m in (detail['meta']?['styles'] as List?) ?? []) {
      final style = m as Map<String, dynamic>;
      final name = (style['name'] as String)
          .toLowerCase()
          .replaceAll(RegExp(r'[^a-z0-9]+'), '_')
          .replaceAll(RegExp(r'^_|_$'), '');
      final type = style['style_type'] as String?;
      if (type == 'FILL') {
        final hex = RegExp(r'#[0-9A-Fa-f]{6,8}')
            .firstMatch(style['description'] as String? ?? '')
            ?.group(0);
        if (hex != null) colors[name] = '0xFF${hex.substring(1).toUpperCase()}';
      } else if (type == 'TEXT') {
        textStyleNames.add(name);
      }
    }
  }

  final buffer = StringBuffer()
    ..writeln('// GENERATED by tool/figma_sync.dart — do not edit by hand.')
    ..writeln('// Re-run the script after changing styles in Figma.')
    ..writeln('import \'package:flutter/material.dart\';')
    ..writeln()
    ..writeln('abstract final class DesignTokens {');
  for (final entry in colors.entries) {
    buffer.writeln('  static const Color ${entry.key} = Color(${entry.value});');
  }
  if (textStyleNames.isNotEmpty) {
    buffer.writeln('  // Text styles defined in Figma: ${textStyleNames.join(', ')}');
  }
  buffer.writeln('}');

  File('lib/design_tokens.dart').writeAsStringSync(buffer.toString());
  // ignore: avoid_print
  print('Synced ${colors.length} colors, ${textStyleNames.length} text styles '
      '→ lib/design_tokens.dart');
}
